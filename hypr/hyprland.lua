-- Workspace -> monitor assignment, mirroring i3's `workspace N output`.
-- M.workspaces, when present, is a list of { first, last, monitor } ranges --
-- see local.lua's template comment. Without it (single-monitor boxes, or a
-- fresh clone before local.lua is edited), workspaces 1-5 default to "eDP-1"
-- (the same generic laptop-panel connector class as the monitor rule above:
-- on a desktop with no eDP-1 the rule just never matches) and 6-10 are left
-- unpinned rather than hardcoded to any one external monitor's description.
if M.workspaces and #M.workspaces > 0 then
    for _, w in ipairs(M.workspaces) do
        for i = w[1], w[2] do
            hl.workspace_rule({ workspace = tostring(i), monitor = w[3] })
        end
    end
else
    for i = 1, 5 do
        hl.workspace_rule({ workspace = tostring(i), monitor = "eDP-1" })
    end
end

-- Terminals: solid-ish when focused, noticeably see-through when not.
-- kitty's own `background_opacity` is left at 1.0 so these two numbers are the whole story.
hl.window_rule({
    name    = "kitty-opacity",
    match   = { class = "(?i)^kitty$" },
    opacity = "0.95 0.85",
})

-- Shadow only where it adds depth. A tiled grid of shadowed windows reads as
-- noise in the 8px gaps; a floating dialog over them reads as lifted.
hl.window_rule({
    name      = "no-shadow-when-tiled",
    match     = { float = false },
    no_shadow = true,
})

hl.window_rule({
    name     = "no-focus-popups",
    match    = { title = "(?i)pop-up" },
    no_focus = true,
})

hl.window_rule({
    name           = "suppress-maximize-events",
    match          = { class = ".*" },
    suppress_event = "maximize",
})

hl.window_rule({
    name  = "fix-xwayland-drags",
    match = {
        class      = "^$",
        title      = "^$",
        xwayland   = true,
        float      = true,
        fullscreen = false,
        pin        = false,
    },
    no_focus = true,
})

-- ripdrag is the drag source ranger cannot be (<C-g> in ranger/rc.conf): a
-- throwaway GTK4 window that exists for the few seconds between picking a file
-- and dropping it onto the browser. Tiling it would reflow the whole layout
-- mid-drag, so it floats; it is pinned because dragging across a workspace
-- switch would otherwise leave it behind.
--
-- Class is the GTK app-id `it.catboy.ripdrag`, NOT `ripdrag` -- confirmed with
-- `hyprctl clients`; a `^ripdrag$` match silently never fires.
--
-- No `size` or `move` here, deliberately, both tested and rejected:
--   * `size` loses to GTK -- ripdrag's window is non-resizable (no --resizable),
--     so it renders at its own size regardless. Size it with ripdrag's own
--     -W/-H in ranger/rc.conf instead, which is where it actually takes.
--   * `move = "cursor <dx> <dy>"` is not understood by the Lua rule parser --
--     the window silently falls back to centred. Absolute `move = "x y"` does
--     work, but lands ~50/80px off the requested spot and would need per-monitor
--     numbers. Centred is predictable, and the pad is small enough (240x180)
--     to grab and drag off the browser without covering much of it.
hl.window_rule({
    name  = "ripdrag-drag-pad",
    match = { class = "(?i)^it\\.catboy\\.ripdrag$" },
    float = true,
    pin   = true,
})
