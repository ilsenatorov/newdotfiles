-- Everything is prefixed with `uwsm app --` so it gets its own systemd unit
-- instead of becoming a child of wayland-wm@hyprland.desktop.service. The
-- Hyprland wiki (Useful-Utilities/Systemd-start) recommends this under UWSM:
-- a crashing helper then cannot take the compositor's unit down with it.
local function app(cmd)
    hl.exec_cmd("uwsm app -- " .. cmd)
end

hl.on("hyprland.start", function()
    -- GTK4/libadwaita and the GTK portal read gsettings, not gtk-4.0/settings.ini.
    -- Without this, file dialogs and GNOME apps stay light on a dark desktop.
    hl.exec_cmd(dotfiles .. "/hypr/scripts/gsettings-theme.sh")

    -- Bar, dashboard corner and notifications all live in one quickshell
    -- instance now -- see quickshell/shell.qml. mako is retired: its
    -- NotificationServer would fight quickshell's for the
    -- org.freedesktop.Notifications D-Bus name if both ran. -n makes this a
    -- no-op if an instance is already running, so a config reload never
    -- stacks two of them.
    app("qs -d -n")
    -- Wallpaper: mpvpaper via wallpaper-daemon.sh, not hyprpaper. The wallpaper
    -- is a looping video (Disco-Elysium-4k.mp4) and hyprpaper only does stills;
    -- mpvpaper covers stills too, so it is the only wallpaper daemon now.
    -- The script reads hypr/wallpaper.conf, written by set-wallpaper.sh.
    -- On for machines by default; set `autostart = { wallpaper = false }` in
    -- local.lua for a machine that doesn't use a video/mpvpaper wallpaper --
    -- otherwise wallpaper-daemon.sh nags with a "mpvpaper is not installed"
    -- notification every login.
    if M.autostart == nil or M.autostart.wallpaper ~= false then
        hl.exec_cmd(dotfiles .. "/hypr/scripts/wallpaper-daemon.sh")
    end
    -- hypridle: disabled by default (no idle timeouts / auto-lock). Its config
    -- stays at hypr/hypridle.conf either way. Re-enable per machine with
    -- `autostart = { hypridle = true }` in local.lua.
    if M.autostart and M.autostart.hypridle then
        app("hypridle")
    end
    -- nm-applet retired: the bar's network module + Network panel (SUPER+N)
    -- replace it, and the tray it rendered into was disabled anyway
    -- (waybar's tray module was commented out).

    -- Polkit agent: NOT started here. hyprpolkitagent ships its own systemd user
    -- unit (WantedBy=graphical-session.target), which is the right mechanism
    -- under UWSM -- enabled once with:
    --   systemctl --user enable --now hyprpolkitagent.service
    -- Its binary lives at /usr/lib/hyprpolkitagent/, not on $PATH, so a
    -- `command -v` guard here would silently fall through to polkit-gnome.

    -- A permanent 3000K filter. wlsunset needed `-T 3001 -t 3000` (a 1-Kelvin
    -- gap) to fake that; hyprsunset does it directly and is runtime-adjustable
    -- via `hyprctl hyprsunset temperature <k>`.
    hl.exec_cmd("sh -c 'command -v hyprsunset >/dev/null "
        .. "&& exec uwsm app -- hyprsunset -t 3000 "
        .. "|| exec uwsm app -- wlsunset -T 3001 -t 3000'")

    -- Clipboard: cliphist stores history, wl-clip-persist keeps the selection
    -- alive after the source window closes (a Wayland-specific papercut).
    hl.exec_cmd("sh -c 'command -v cliphist >/dev/null && { "
        .. "uwsm app -- wl-paste --type text --watch cliphist store & "
        .. "uwsm app -- wl-paste --type image --watch cliphist store & }'")
    hl.exec_cmd("sh -c 'command -v wl-clip-persist >/dev/null "
        .. "&& exec uwsm app -- wl-clip-persist --clipboard regular'")
end)



